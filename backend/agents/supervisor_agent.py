"""
Supervisor Agent — Central orchestrator for dynamic multi-agent investigation.

The Supervisor analyzes incoming security events, develops investigation plans,
dynamically selects specialist agents, monitors execution, and decides when
an investigation is complete.
"""

from __future__ import annotations

import logging
from typing import Literal, Optional

from langchain_groq import ChatGroq
from langchain_core.prompts import PromptTemplate
from pydantic import BaseModel, Field

from agents.base_agent import BaseAgent
from config.settings import settings
from schemas.schemas import IncidentState, Severity

logger = logging.getLogger(__name__)


# ── Investigation Plan Output Schema ──────────────────────────────────────────

class InvestigationPlan(BaseModel):
    """Structured investigation plan generated by the Supervisor."""
    
    alert_classification: Literal[
        "brute_force",
        "malware",
        "phishing",
        "port_scan",
        "c2_communication",
        "data_exfiltration",
        "privilege_escalation",
        "lateral_movement",
        "reconnaissance",
        "unknown"
    ] = Field(description="Primary threat classification")
    
    urgency: Literal["low", "medium", "high", "critical"] = Field(
        description="Investigation urgency based on initial assessment"
    )
    
    required_agents: list[Literal[
        "enrichment",
        "mitre",
        "threat_hunting",
        "digital_forensics",
        "correlation",
        "triage",
        "decision",
        "reviewer"
    ]] = Field(description="Ordered list of agents needed for this investigation")
    
    parallel_agents: list[list[str]] = Field(
        default_factory=list,
        description="Groups of agents that can run in parallel, e.g. [['enrichment', 'mitre'], ['hunting']]"
    )
    
    reasoning: str = Field(description="Why this investigation plan was chosen")
    
    key_questions: list[str] = Field(
        default_factory=list,
        description="Specific questions this investigation should answer"
    )
    
    estimated_complexity: Literal["simple", "moderate", "complex"] = Field(
        description="Estimated investigation complexity"
    )


class SupervisorDecision(BaseModel):
    """Decision on whether to continue investigating or conclude."""
    
    action: Literal["continue", "conclude", "escalate"] = Field(
        description="Next action: continue investigating, conclude investigation, or escalate to human"
    )
    
    reasoning: str = Field(description="Why this decision was made")
    
    next_agents: list[str] = Field(
        default_factory=list,
        description="If continuing, which agents to invoke next"
    )
    
    missing_evidence: list[str] = Field(
        default_factory=list,
        description="What evidence is still needed"
    )
    
    confidence: float = Field(
        ge=0.0, le=1.0,
        description="Confidence in the current findings (0-1)"
    )


# ── Supervisor Agent ──────────────────────────────────────────────────────────

class SupervisorAgent(BaseAgent):
    """
    Central orchestrator that:
    1. Analyzes raw alerts and creates investigation plans
    2. Dynamically selects which agents to invoke
    3. Monitors investigation progress
    4. Decides when investigation is complete
    5. Handles incomplete or conflicting findings
    """

    name = "supervisor_agent"

    def __init__(self):
        self.llm = ChatGroq(
            model=settings.llm_model,
            temperature=0.2,  # Slightly higher for planning creativity
            api_key=settings.groq_api_key
        )
        
        # Planning LLM with structured output
        self.planning_llm = self.llm.with_structured_output(InvestigationPlan)
        self.decision_llm = self.llm.with_structured_output(SupervisorDecision)
        
        self.planning_prompt = PromptTemplate(
            template="""You are the Supervisor of a Security Operations Center (SOC) multi-agent system.

Analyze this security alert and create an investigation plan.

### Raw Alert
{raw_alert}

### Initial Extraction (if available)
Events: {num_events}
IOCs extracted: {ioc_summary}
Severity hint: {severity_hint}

### Your Task
1. Classify the alert type (brute_force, malware, phishing, etc.)
2. Assess urgency (low/medium/high/critical)
3. Select which specialist agents are needed:
   - enrichment: Threat intelligence lookup for IOCs
   - mitre: Map behaviors to MITRE ATT&CK framework
   - threat_hunting: Search historical incidents for patterns
   - digital_forensics: Build attack timeline and reconstruct chain
   - correlation: Find relationships across events
   - triage: Calculate risk score
   - decision: Generate final verdict
   - reviewer: Validate findings independently

4. Group agents that can run in parallel (e.g., enrichment and MITRE don't depend on each other)
5. Identify key questions to answer
6. Estimate complexity

### Guidelines
- Port scans and reconnaissance: simple investigation (enrichment, MITRE, triage, decision)
- Malware/phishing: moderate (add threat_hunting, reviewer)
- Data exfiltration/ransomware: complex (add digital_forensics, full analysis)
- Unknown alerts: start simple, supervisor will decide to expand if needed

Provide a structured investigation plan.
""",
            input_variables=["raw_alert", "num_events", "ioc_summary", "severity_hint"]
        )
        
        self.decision_prompt = PromptTemplate(
            template="""You are the Supervisor reviewing an ongoing investigation.

### Investigation Context
Raw Alert: {raw_alert}
Plan: {plan_summary}
Completed Agents: {completed_agents}
Current Iteration: {iteration}/{max_iterations}

### Findings So Far
IOC Enrichments: {enrichment_count} IOCs analyzed
- Malicious: {malicious_count}
- Suspicious: {suspicious_count}
- Benign: {benign_count}

MITRE Mappings: {mitre_count} techniques identified
Triage Score: {triage_score}/100 ({triage_severity})
Decision: {decision}

### Agent Execution Trace
{agent_trace}

### Your Task
Decide whether to:
1. CONTINUE: Request additional investigation (specify which agents and why)
2. CONCLUDE: Investigation is complete with sufficient evidence
3. ESCALATE: Conflicting evidence or uncertainty requires human analyst

### Decision Criteria
- CONCLUDE if: Clear verdict with supporting evidence, no major gaps, confidence > 0.7
- CONTINUE if: Missing evidence, unanswered questions, suspicious patterns need hunting
- ESCALATE if: Conflicting findings, critical severity with uncertainty, or max iterations reached

Provide your decision with clear reasoning.
""",
            input_variables=[
                "raw_alert", "plan_summary", "completed_agents", "iteration", "max_iterations",
                "enrichment_count", "malicious_count", "suspicious_count", "benign_count",
                "mitre_count", "triage_score", "triage_severity", "decision", "agent_trace"
            ]
        )

    async def create_investigation_plan(self, state: IncidentState) -> InvestigationPlan:
        """
        Analyze the alert and create an investigation plan.
        Called at the start of the workflow.
        """
        # Summarize initial extraction
        ioc_summary = "None"
        if state.events and state.events[0].extracted_iocs:
            iocs = state.events[0].extracted_iocs
            ioc_summary = f"{len(iocs)} IOCs ({', '.join(f'{i.type.value}:{i.value}' for i in iocs[:3])}...)"
        
        severity_hint = "unknown"
        if state.events and state.events[0].severity_hint:
            severity_hint = state.events[0].severity_hint.value

        try:
            chain = self.planning_prompt | self.planning_llm
            plan = await chain.ainvoke({
                "raw_alert": state.raw_alert,
                "num_events": len(state.events),
                "ioc_summary": ioc_summary,
                "severity_hint": severity_hint
            })
            
            logger.info(
                f"Investigation plan created: {plan.alert_classification} "
                f"(urgency: {plan.urgency}, complexity: {plan.estimated_complexity})"
            )
            logger.info(f"Required agents: {', '.join(plan.required_agents)}")
            
            return plan
            
        except Exception as e:
            logger.error(f"Failed to create investigation plan: {e}")
            # Fallback to default comprehensive plan
            return InvestigationPlan(
                alert_classification="unknown",
                urgency="medium",
                required_agents=["enrichment", "mitre", "correlation", "triage", "decision"],
                parallel_agents=[["enrichment", "mitre"], ["correlation"], ["triage"], ["decision"]],
                reasoning=f"Fallback plan due to error: {e}",
                key_questions=["What is the threat?", "What is the risk?"],
                estimated_complexity="moderate"
            )

    async def should_continue_investigation(
        self, 
        state: IncidentState,
        completed_agents: list[str],
        max_iterations: int = 3
    ) -> SupervisorDecision:
        """
        Evaluate current findings and decide whether to continue investigating.
        Called after each agent execution phase.
        """
        # Count findings
        malicious_count = sum(1 for e in state.enrichments if e.final_verdict.value == "malicious")
        suspicious_count = sum(1 for e in state.enrichments if e.final_verdict.value == "suspicious")
        benign_count = sum(1 for e in state.enrichments if e.final_verdict.value == "benign")
        
        triage_score = state.triage.score if state.triage else 0
        triage_severity = state.triage.severity.value if state.triage else "unknown"
        
        # Format agent trace
        agent_trace_str = "\n".join([
            f"- {step.agent_name}: {step.status.value} ({step.duration_ms}ms)"
            for step in state.agent_trace[-5:]  # Last 5 agents
        ])
        
        # Get current iteration
        iteration = getattr(state, 'supervisor_iteration', 1)
        
        try:
            chain = self.decision_prompt | self.decision_llm
            decision = await chain.ainvoke({
                "raw_alert": state.raw_alert[:200],
                "plan_summary": getattr(state, 'investigation_plan_summary', 'N/A'),
                "completed_agents": ", ".join(completed_agents),
                "iteration": iteration,
                "max_iterations": max_iterations,
                "enrichment_count": len(state.enrichments),
                "malicious_count": malicious_count,
                "suspicious_count": suspicious_count,
                "benign_count": benign_count,
                "mitre_count": len(state.mitre_mappings),
                "triage_score": triage_score,
                "triage_severity": triage_severity,
                "decision": state.decision or "pending",
                "agent_trace": agent_trace_str or "No agents executed yet"
            })
            
            logger.info(
                f"Supervisor decision: {decision.action} "
                f"(confidence: {decision.confidence:.2f})"
            )
            if decision.next_agents:
                logger.info(f"Next agents: {', '.join(decision.next_agents)}")
            
            return decision
            
        except Exception as e:
            logger.error(f"Supervisor decision failed: {e}")
            # Conservative fallback: conclude if we have a decision, otherwise continue
            if state.decision and state.triage:
                return SupervisorDecision(
                    action="conclude",
                    reasoning=f"Fallback decision: investigation has verdict and triage (error: {e})",
                    confidence=0.5
                )
            else:
                return SupervisorDecision(
                    action="continue",
                    reasoning=f"Fallback decision: continue to complete investigation (error: {e})",
                    next_agents=["triage", "decision"],
                    confidence=0.3
                )

    async def _process(self, state: IncidentState) -> IncidentState:
        """
        Supervisor's main execution - called by the workflow for initial planning.
        """
        # Create investigation plan
        plan = await self.create_investigation_plan(state)
        
        # Store plan in state (as metadata for now, can be formalized in schema later)
        state.investigation_plan_summary = (
            f"{plan.alert_classification} ({plan.urgency} urgency, "
            f"{plan.estimated_complexity} complexity)"
        )
        
        # Initialize supervisor iteration counter
        if not hasattr(state, 'supervisor_iteration'):
            state.supervisor_iteration = 1
        
        # Store plan details for routing logic
        state.supervisor_plan = plan.model_dump()
        
        return state
