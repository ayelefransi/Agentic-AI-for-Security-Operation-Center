"""
Supervisor Agent — Central orchestrator for dynamic multi-agent investigation.

The Supervisor analyzes incoming security events, develops investigation plans,
dynamically selects specialist agents, monitors execution, and decides when
an investigation is complete.
"""

from __future__ import annotations

import json
import logging
import os
import re
from typing import Literal, Optional

from langchain_groq import ChatGroq
from langchain_core.prompts import PromptTemplate
from pydantic import BaseModel, Field

from agents.base_agent import BaseAgent
from config.settings import settings
from schemas.schemas import IncidentState, Severity

logger = logging.getLogger(__name__)


# ── Investigation Plan Output Schema ──────────────────────────────────────────

VALID_CLASSIFICATIONS = [
    "brute_force",
    "malware",
    "phishing",
    "port_scan",
    "c2_communication",
    "data_exfiltration",
    "privilege_escalation",
    "lateral_movement",
    "reconnaissance",
    "unknown"
]

VALID_URGENCIES = ["low", "medium", "high", "critical"]
VALID_COMPLEXITIES = ["simple", "moderate", "complex"]
VALID_AGENTS = [
    "enrichment",
    "mitre",
    "threat_hunting",
    "digital_forensics",
    "correlation",
    "triage",
    "decision",
    "reviewer"
]

class InvestigationPlan(BaseModel):
    """Structured investigation plan generated by the Supervisor."""
    
    alert_classification: str = Field(
        default="unknown",
        description="Primary threat classification"
    )
    
    urgency: str = Field(
        default="medium",
        description="Investigation urgency based on initial assessment"
    )
    
    required_agents: list[str] = Field(
        default_factory=lambda: ["enrichment", "mitre", "correlation", "triage", "decision"],
        description="Ordered list of agents needed for this investigation"
    )
    
    parallel_agents: list[list[str]] = Field(
        default_factory=lambda: [["enrichment", "mitre"], ["correlation"], ["triage"], ["decision"]],
        description="Groups of agents that can run in parallel"
    )
    
    reasoning: str = Field(
        default="Standard SOC investigation protocol",
        description="Why this investigation plan was chosen"
    )
    
    key_questions: list[str] = Field(
        default_factory=list,
        description="Specific questions this investigation should answer"
    )
    
    estimated_complexity: str = Field(
        default="moderate",
        description="Estimated investigation complexity (simple, moderate, complex)"
    )


class SupervisorDecision(BaseModel):
    """Decision on whether to continue investigating or conclude."""
    
    action: str = Field(
        default="conclude",
        description="Next action: continue investigating, conclude investigation, or escalate to human"
    )
    
    reasoning: str = Field(
        default="Investigation complete with sufficient evidence.",
        description="Why this decision was made"
    )
    
    next_agents: list[str] = Field(
        default_factory=list,
        description="If continuing, which agents to invoke next"
    )
    
    missing_evidence: list[str] = Field(
        default_factory=list,
        description="What evidence is still needed"
    )
    
    confidence: float = Field(
        default=0.8,
        ge=0.0, le=1.0,
        description="Confidence in the current findings (0-1)"
    )


# ── Supervisor Agent ──────────────────────────────────────────────────────────

class SupervisorAgent(BaseAgent):
    """
    Central orchestrator that:
    1. Analyzes raw alerts and creates investigation plans
    2. Dynamically selects which agents to invoke
    3. Monitors investigation progress
    4. Decides when investigation is complete
    5. Handles incomplete or conflicting findings
    """

    name = "supervisor_agent"

    def __init__(self):
        self.llm = ChatGroq(
            model=settings.llm_model,
            temperature=0.1,
            api_key=settings.groq_api_key or os.environ.get("GROQ_API_KEY", "")
        )
        
        self.planning_prompt = PromptTemplate(
            template="""You are the Supervisor of a Security Operations Center (SOC) multi-agent system.
Analyze this security alert and return an investigation plan as a strict JSON object.

### Raw Alert
{raw_alert}

### Initial Extraction (if available)
Events: {num_events}
IOCs extracted: {ioc_summary}
Severity hint: {severity_hint}

### Classification Guidelines
- Alert Classification must be one of: brute_force, malware, phishing, port_scan, c2_communication, data_exfiltration, privilege_escalation, lateral_movement, reconnaissance, unknown
- Urgency must be one of: low, medium, high, critical
- Complexity must be one of: simple, moderate, complex
- Available specialist agents: enrichment, mitre, threat_hunting, digital_forensics, correlation, triage, decision, reviewer

Respond ONLY with a valid JSON object matching this exact schema:
{{
  "alert_classification": "brute_force",
  "urgency": "high",
  "required_agents": ["enrichment", "mitre", "correlation", "triage", "decision"],
  "parallel_agents": [["enrichment", "mitre"], ["correlation"], ["triage"], ["decision"]],
  "reasoning": "High-volume authentication failures require threat intelligence lookup and correlation.",
  "key_questions": ["Is the source IP a known scanner?", "Were any attempts successful?"],
  "estimated_complexity": "moderate"
}}
Do NOT wrap in markdown code blocks or add explanatory text.
""",
            input_variables=["raw_alert", "num_events", "ioc_summary", "severity_hint"]
        )
        
        self.decision_prompt = PromptTemplate(
            template="""You are the Supervisor reviewing an ongoing SOC investigation.
Review the current progress and findings, then decide whether to CONTINUE, CONCLUDE, or ESCALATE.

### Investigation Context
Raw Alert: {raw_alert}
Plan: {plan_summary}
Completed Agents: {completed_agents}
Current Iteration: {iteration}/{max_iterations}

### Findings So Far
IOC Enrichments: {enrichment_count} IOCs analyzed
- Malicious: {malicious_count}
- Suspicious: {suspicious_count}
- Benign: {benign_count}
MITRE Mappings: {mitre_count} techniques identified
Triage Score: {triage_score}/100 ({triage_severity})
Decision: {decision}

### Agent Execution Trace
{agent_trace}

### Decision Guidelines
- "conclude": Investigation is complete, verdict is established, and primary agents have finished.
- "continue": Missing critical evidence or further correlation/hunting is required.
- "escalate": Severe ambiguity, conflicting critical telemetry, or high-risk unknown behavior.

Respond ONLY with a valid JSON object matching this exact schema:
{{
  "action": "conclude",
  "reasoning": "Investigation has gathered comprehensive IOC verdicts and computed the triage score.",
  "next_agents": [],
  "missing_evidence": [],
  "confidence": 0.85
}}
Do NOT wrap in markdown code blocks or add explanatory text.
""",
            input_variables=[
                "raw_alert", "plan_summary", "completed_agents", "iteration", "max_iterations",
                "enrichment_count", "malicious_count", "suspicious_count", "benign_count",
                "mitre_count", "triage_score", "triage_severity", "decision", "agent_trace"
            ]
        )

    def _heuristic_plan(self, raw_alert: str, severity_hint: str) -> InvestigationPlan:
        """Deterministic heuristic plan when LLM call fails or times out."""
        text = raw_alert.lower()
        
        if any(w in text for w in ["brute", "failed login", "ssh", "rdp", "eventid: 4625", "4625", "bad password"]):
            classification = "brute_force"
            urgency = "high"
            complexity = "moderate"
        elif any(w in text for w in ["scan", "nmap", "syn flood", "sweep", "probed"]):
            classification = "port_scan"
            urgency = "medium"
            complexity = "simple"
        elif any(w in text for w in ["c2", "command and control", "beacon", "cobalt"]):
            classification = "c2_communication"
            urgency = "critical"
            complexity = "complex"
        elif any(w in text for w in ["malware", "trojan", "ransomware", "mimikatz", "powershell -enc", "meterpreter"]):
            classification = "malware"
            urgency = "critical"
            complexity = "complex"
        elif any(w in text for w in ["phish", "spoof", "dkim", "spf fail", "suspicious email"]):
            classification = "phishing"
            urgency = "medium"
            complexity = "moderate"
        elif any(w in text for w in ["exfiltration", "exfil", "data leak", "mega.nz", "dropbox"]):
            classification = "data_exfiltration"
            urgency = "critical"
            complexity = "complex"
        elif any(w in text for w in ["privilege", "sudo", "privesc", "uac bypass"]):
            classification = "privilege_escalation"
            urgency = "high"
            complexity = "moderate"
        else:
            classification = "reconnaissance" if "recon" in text else "unknown"
            urgency = "high" if severity_hint.lower() in ("high", "critical") else "medium"
            complexity = "moderate"

        return InvestigationPlan(
            alert_classification=classification,
            urgency=urgency,
            required_agents=["enrichment", "mitre", "correlation", "triage", "decision"],
            parallel_agents=[["enrichment", "mitre"], ["correlation"], ["triage"], ["decision"]],
            reasoning=f"Automated SOC heuristic: detected {classification} indicators requiring standard multi-agent pipeline.",
            key_questions=["What is the threat origin?", "Are any associated IOCs malicious?", "What is the overall risk score?"],
            estimated_complexity=complexity
        )

    async def create_investigation_plan(self, state: IncidentState) -> InvestigationPlan:
        """
        Analyze the alert and create an investigation plan.
        Called at the start of the workflow.
        """
        ioc_summary = "None"
        if state.events and state.events[0].extracted_iocs:
            iocs = state.events[0].extracted_iocs
            ioc_summary = f"{len(iocs)} IOCs ({', '.join(f'{i.type.value}:{i.value}' for i in iocs[:3])}...)"
        
        severity_hint = "unknown"
        if state.events and state.events[0].severity_hint:
            severity_hint = state.events[0].severity_hint.value

        try:
            response = await (self.planning_prompt | self.llm).ainvoke({
                "raw_alert": state.raw_alert[:2000],
                "num_events": len(state.events),
                "ioc_summary": ioc_summary,
                "severity_hint": severity_hint
            })
            
            raw_text = response.content if hasattr(response, "content") else str(response)
            json_match = re.search(r'\{.*\}', raw_text, re.DOTALL)
            
            if json_match:
                data = json.loads(json_match.group(0))
                
                # Sanitize fields
                cls_val = str(data.get("alert_classification", "unknown")).lower()
                if cls_val not in VALID_CLASSIFICATIONS:
                    cls_val = "unknown"
                    
                urg_val = str(data.get("urgency", "medium")).lower()
                if urg_val not in VALID_URGENCIES:
                    urg_val = "medium"
                    
                comp_val = str(data.get("estimated_complexity", "moderate")).lower()
                if comp_val not in VALID_COMPLEXITIES:
                    comp_val = "moderate"
                    
                req_agents = [
                    a for a in data.get("required_agents", [])
                    if a in VALID_AGENTS
                ]
                if not req_agents:
                    req_agents = ["enrichment", "mitre", "correlation", "triage", "decision"]
                    
                parallel = data.get("parallel_agents")
                if not parallel or not isinstance(parallel, list):
                    parallel = [["enrichment", "mitre"], ["correlation"], ["triage"], ["decision"]]

                plan = InvestigationPlan(
                    alert_classification=cls_val,
                    urgency=urg_val,
                    required_agents=req_agents,
                    parallel_agents=parallel,
                    reasoning=str(data.get("reasoning", "Supervisor dynamic investigation plan")),
                    key_questions=data.get("key_questions", []),
                    estimated_complexity=comp_val
                )
                logger.info(f"Investigation plan created via LLM: {plan.alert_classification} (urgency: {plan.urgency})")
                return plan
                
        except Exception as e:
            logger.warning(f"LLM planning failed ({e}), using heuristic fallback plan")

        return self._heuristic_plan(state.raw_alert, severity_hint)

    async def should_continue_investigation(
        self, 
        state: IncidentState,
        completed_agents: list[str],
        max_iterations: int = 3
    ) -> SupervisorDecision:
        """
        Evaluate current findings and decide whether to continue investigating.
        Called after each agent execution phase.
        """
        malicious_count = sum(1 for e in state.enrichments if getattr(e.final_verdict, "value", str(e.final_verdict)) == "malicious")
        suspicious_count = sum(1 for e in state.enrichments if getattr(e.final_verdict, "value", str(e.final_verdict)) == "suspicious")
        benign_count = sum(1 for e in state.enrichments if getattr(e.final_verdict, "value", str(e.final_verdict)) == "benign")
        
        triage_score = state.triage.score if state.triage else 0
        triage_severity = state.triage.severity.value if state.triage and hasattr(state.triage.severity, "value") else (state.triage.severity if state.triage else "unknown")
        
        agent_trace_str = "\n".join([
            f"- {step.agent_name}: {getattr(step.status, 'value', str(step.status))} ({step.duration_ms}ms)"
            for step in state.agent_trace[-5:]
        ])
        
        iteration = state.supervisor_iteration or 1
        
        try:
            response = await (self.decision_prompt | self.llm).ainvoke({
                "raw_alert": state.raw_alert[:300],
                "plan_summary": state.investigation_plan_summary or 'Standard SOC Investigation',
                "completed_agents": ", ".join(completed_agents),
                "iteration": iteration,
                "max_iterations": max_iterations,
                "enrichment_count": len(state.enrichments),
                "malicious_count": malicious_count,
                "suspicious_count": suspicious_count,
                "benign_count": benign_count,
                "mitre_count": len(state.mitre_mappings),
                "triage_score": triage_score,
                "triage_severity": triage_severity,
                "decision": state.decision or "pending",
                "agent_trace": agent_trace_str or "No agents executed yet"
            })
            
            raw_text = response.content if hasattr(response, "content") else str(response)
            json_match = re.search(r'\{.*\}', raw_text, re.DOTALL)
            if json_match:
                data = json.loads(json_match.group(0))
                action = str(data.get("action", "conclude")).lower()
                if action not in ["continue", "conclude", "escalate"]:
                    action = "conclude"
                
                decision = SupervisorDecision(
                    action=action,
                    reasoning=str(data.get("reasoning", "Supervisor evaluation")),
                    next_agents=data.get("next_agents", []),
                    missing_evidence=data.get("missing_evidence", []),
                    confidence=float(data.get("confidence", 0.8))
                )
                logger.info(f"Supervisor decision via LLM: {decision.action} (confidence: {decision.confidence:.2f})")
                return decision
        except Exception as e:
            logger.warning(f"Supervisor decision LLM failed ({e}), applying rule-based decision")

        # Deterministic fallback decision logic
        if iteration >= max_iterations:
            return SupervisorDecision(
                action="conclude",
                reasoning=f"Max supervisor iterations ({max_iterations}) reached. Finalizing report.",
                confidence=0.85
            )

        if state.decision and state.triage:
            return SupervisorDecision(
                action="conclude",
                reasoning="Investigation has produced both triage risk score and final verdict with supporting evidence.",
                confidence=0.9
            )

        # If decision or triage not yet done, continue to complete them
        if "decision" not in completed_agents:
            return SupervisorDecision(
                action="continue",
                reasoning="Final decision agent has not executed yet. Continuing pipeline.",
                next_agents=["triage", "decision"],
                confidence=0.7
            )

        return SupervisorDecision(
            action="conclude",
            reasoning="Core investigation pipeline completed successfully.",
            confidence=0.85
        )

    async def _process(self, state: IncidentState) -> IncidentState:
        """
        Supervisor's main execution - called by the workflow for initial planning.
        """
        plan = await self.create_investigation_plan(state)
        
        state.investigation_plan_summary = (
            f"{plan.alert_classification} ({plan.urgency} urgency, "
            f"{plan.estimated_complexity} complexity)"
        )
        
        state.supervisor_iteration = 0
        state.supervisor_plan = plan.model_dump()
        
        return state
